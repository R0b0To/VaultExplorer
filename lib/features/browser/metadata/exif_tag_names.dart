  static String ifd0(int tag) =>
      _ifd0[tag] ?? _exif[tag] ?? 'Tag 0x${_hex(tag)}';
  static String exif(int tag) => _exif[tag] ?? _ifd0[tag] ?? 'Tag 0x${_hex(tag)}';
  static String gps(int tag) => _gps[tag] ?? 'GPS tag 0x${_hex(tag)}';
  static String interop(int tag) => _interop[tag] ?? 'Tag 0x${_hex(tag)}';

  static String _hex(int tag) => tag.toRadixString(16).toUpperCase().padLeft(4, '0');

