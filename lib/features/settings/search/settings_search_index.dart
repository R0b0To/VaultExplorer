SettingsSearchEntry _e(
  String id,
  SettingsDestination destination,
  SettingsText title, {
  SettingsText? section,
  SettingsText? fallback,
  List<SettingsText> details = const [],
  List<String> keywords = const [],
  bool scrollTo = true,
  int? minSdk,
}) {
  return SettingsSearchEntry(
    id: id,
    destination: destination,
    title: title,
    section: section,
    fallback: fallback,
    details: details,
    keywords: keywords,
    scrollTo: scrollTo,
    minSdk: minSdk,
  );
}

/// Resolves the registry for [l10n]'s language. [androidSdkInt] hides entries
/// whose row isn't shown on the device's Android version.
List<ResolvedSettingsEntry> resolveSettingsSearchIndex(
  AppLocalizations l10n, {
  required int androidSdkInt,
}) {
  return [
    for (final entry in kSettingsSearchEntries)
      if (entry.minSdk == null || androidSdkInt >= entry.minSdk!)
        entry.resolve(l10n),
  ];
}
